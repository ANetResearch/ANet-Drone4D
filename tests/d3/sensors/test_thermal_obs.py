def test_thermal_obs_is_projection_with_delivered_bytes() -> None:
    from awr.sensorsvc.poses import Mount
    from awr.sim.sensors.frames import R_to_quat_xyzw, mount_R

    ck = _ck()
    mount = Mount((0.12, 0.0, -0.08), (2.0, 30.0, -15.0))
    rec, blocks = _thermal_record(ck, mount=mount, gimbal=(math.radians(10.0), math.radians(-45.0), 0.0))
    assert errors(FRAME_V1, rec) == []
    tc = rec["agent_view"]["temp_ck"]
    o = thermal_obs(rec, blocks)
    assert o["temp_ck"] is blocks[tc["ref"]]                                         # 同一 bytes 对象：交付字节即帧记录载荷
    assert hashlib.sha256(o["temp_ck"]).hexdigest() == tc["sha256"]
    assert np.array_equal(decode_thermal_obs(o), ck)
    assert (o["width"], o["height"], o["seq"], o["t_mid_ns"], o["codec"]) == (64, 48, 7, 700_000_000, "radiometric_u16")
    assert o["K"] == rec["agent_view"]["K"] and o["dist"] == [0.0] * 5
    q = np.asarray(R_to_quat_xyzw(mount_R(mount.rpy_deg)), np.float64)
    q = -q if q[3] < 0 else q
    assert np.allclose(o["mount_nominal"]["q_bs_xyzw"], q, atol=1e-12) and o["mount_nominal"]["t_bs_m"] == [0.12, 0.0, -0.08]
    assert o["gimbal_reading"] == {"roll_deg": 0.0, "pitch_deg": pytest.approx(-45.0), "yaw_deg": pytest.approx(10.0)}
    doc = _observation([o])
    assert list(bench_validator("obs").iter_errors(doc)) == []
    # 白名单是帧记录 agent_view 的投影（codec 取自 agent_view.temp_ck.codec），与真值、内部分区不相交
    th = set(load("bench/obs.v1.schema.json")["$defs"]["ThermalObs"]["properties"])
    fr = load(FRAME_V1)["properties"]
    assert th - {"codec"} <= set(fr["agent_view"]["properties"])
    assert not th & (set(fr["ground_truth"]["properties"]) | set(fr["internal"]["properties"]))
    with pytest.raises(ValueError):
        thermal_obs(rec, {**blocks, tc["ref"]: bytes(blocks[tc["ref"]][:-1]) + bytes([blocks[tc["ref"]][-1] ^ 0xFF])})   # sha256 不符
    cam = copy.deepcopy(rec)
    cam["kind"] = "camera"
    with pytest.raises(ValueError):
        thermal_obs(cam, blocks)


