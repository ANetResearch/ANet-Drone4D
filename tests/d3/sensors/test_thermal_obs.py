# ---------------------------------------------------------------- dT_app_k 构造用例（M25-AC-049）

@pytest.mark.parametrize("case", ["person_night", "vehicle_fog_1km"])
def test_dT_app_k_matches_analytic_construction(case: str) -> None:
    """平板场景：背景为 ε = 0.95 地面（T_air − 1 K），实体为 ε = 0.98 的 305.15 K 表面（人员夜间）或 ε = 0.90 的 330 K 表面
    （车辆发动机区，雾中 1 km），均按 CPU 辐射链（`sensor_radiance` + Planck 表反变换）生成无噪表观温度；`dT_app_k` 与 float64
    解析式之差 ≤ 0.1 K。"""
    table = rad.planck_table()
    if case == "person_night":
        env, d_m, t_obj, eps_obj, n_obj = rad.ThermalEnv(288.15, cloud=0.0, rh=0.5), 120.0, 305.15, 0.98, 0.3
    else:
        env, d_m, t_obj, eps_obj, n_obj = rad.ThermalEnv(283.15, cloud=1.0, rh=0.9, fog_visibility_km=2.0), 1000.0, 330.0, 0.90, 0.0
    t_bg, eps_bg, n_bg = env.t_air_k - 1.0, 0.95, 1.0
    H, W = 60, 80
    inst = np.zeros((H, W), np.uint16)
    inst[20:44, 30:42] = 1
    m = inst == 1
    L = rad.sensor_radiance(table, np.where(m, t_obj, t_bg), np.where(m, eps_obj, eps_bg), np.where(m, n_obj, n_bg), np.full((H, W), d_m), env)
    t_app = table.temperature(L)
    objs = tr.thermal_objects(t_app, inst, inst.copy(), np.where(m, 32, 1).astype(np.uint8), [PERSON])

    def exact(t_s, eps, n_z) -> float:
        B = rad.band_radiance_exact
        w = min(1.0, max(0.0, n_z))
        tau = math.exp(-env.beta_per_km * d_m * 1e-3)
        l_obj = eps * B(t_s) + (1.0 - eps) * (w * B(env.sky_k) + (1.0 - w) * B(env.t_air_k))
        return float(rad.band_temperature_exact(tau * l_obj + (1.0 - tau) * B(env.t_air_k)))

    want = exact(t_obj, eps_obj, n_obj) - exact(t_bg, eps_bg, n_bg)
    assert len(objs) == 1 and "no_ring" not in objs[0]["flags"]
    assert abs(objs[0]["dT_app_k"] - want) <= DT_TOL_K, (objs[0]["dT_app_k"], want)
    assert abs(want) >= 1.0                                                       # 构造满足识别判据 |dT_app_k| ≥ 1 K 的量级


