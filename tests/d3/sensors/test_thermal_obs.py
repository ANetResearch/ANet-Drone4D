def test_ranked_runs_reject_agc_jpeg() -> None:
    assert check_thermal_codec("radiometric_u16", ranked=True) == "radiometric_u16"
    assert check_thermal_codec("agc_jpeg", ranked=False) == "agc_jpeg"
