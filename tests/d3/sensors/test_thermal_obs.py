def test_golden_vectors_host_and_sdk_roundtrip() -> None:
    from anet4d import wire as sdk

    from awr.agentsdk.env.obs_audit import ObsAudit

    vec = _vectors()
    if os.environ.get("AWR_REGEN_GOLDEN") == "1":
        GOLD.mkdir(parents=True, exist_ok=True)
        for name, b in vec.items():
            (GOLD / name).write_text(b.decode() if name.endswith(".json") else _hex(b))
    meta = json.loads((GOLD / "vectors.json").read_text())
    assert (GOLD / "vectors.json").read_bytes() == vec["vectors.json"]
    raw, zst, frame = _gold("temp_ck_8x6.u16le"), _gold("temp_ck_8x6.zst"), _gold("obs_thermal_8x6")
    for name, b in (("temp_ck_8x6.u16le", raw), ("temp_ck_8x6.zst", zst), ("obs_thermal_8x6", frame)):
        assert hashlib.sha256(b).hexdigest() == meta["sha256"][name]
    ck = np.frombuffer(raw, "<u2").reshape(meta["height"], meta["width"])
    assert np.array_equal(ck, _ck_pattern(8, 6))
    for key, kelvin in meta["samples_k"].items():
        i, j = (int(v) for v in key.split(","))
        assert ck[i, j] / 100 == pytest.approx(kelvin, abs=1e-9)
    # 编码：zstd 级别 3 单帧字节确定（zstandard 版本由 requirements*.lock 固定）；宿主与 SDK 线编码逐字节一致
    assert tr.encode_temp_ck(ck) == zst and np.array_equal(tr.decode_temp_ck(zst, 8, 6), ck)
    body = _observation([_golden_obs(_ck_pattern(8, 6))])
    assert encode_frame(T.OBS, body) == frame and sdk.encode_frame(T.OBS, body) == frame
    # 解码往返：bytes 以 msgpack bin 携带，解出对象与原对象相同
    doc = decode_body(T.OBS, frame[8:])
    assert doc == body and isinstance(doc["obs"]["sensors"][SID][0]["temp_ck"], bytes)
    o = doc["obs"]["sensors"][SID][0]
    assert list(o) == list(load("bench/obs.v1.schema.json")["$defs"]["ThermalObs"]["properties"])
    assert np.array_equal(decode_thermal_obs(o), ck) and thermal_payload_ok(o)
    assert list(bench_validator("obs").iter_errors(doc)) == []
    audit = ObsAudit()
    audit.check_body(T.OBS, frame[8:], uav=UAV)
    assert audit.passed and audit.checked == 1 and audit.unknown_fields == 0


