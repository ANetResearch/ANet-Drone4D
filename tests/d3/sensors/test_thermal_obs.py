def test_recorder_archives_delivered_bytes(tmp_path: Path) -> None:
    from mcap.reader import make_reader

    from awr.agentsdk.env.recorder import RAW_TOPIC_PATTERNS, EnvRecorder, RecorderOptions
    from awr.bench.recorder.channels import decode_thermal_message, parse_obs_topic, thermal_topic
    from awr.bench.recorder.read import FrameStore

    run = tmp_path / "run-th"
    rec_ = EnvRecorder(run, options=RecorderOptions(queue_msgs=4))
    sent: dict[int, tuple[bytes, str, np.ndarray]] = {}
    for k in (1, 2, 3):
        ck = _ck(64, 48, seed=k)
        rec, blocks = _thermal_record(ck, seq=k)
        o = thermal_obs(rec, blocks)
        msg = _observation([o], k=k)
        assert list(bench_validator("obs").iter_errors(msg)) == []
        rec_.on_obs(UAV, k, msg)
        sent[k] = (o["temp_ck"], rec["agent_view"]["temp_ck"]["sha256"], ck)
    summ = rec_.finish()
    topic = thermal_topic(UAV, SID)
    assert summ["dropped"] == 0 and summ["frames"] == {f"{UAV}/{SID}": 3}
    assert any(re.match(p, topic) for p in RAW_TOPIC_PATTERNS) and parse_obs_topic(topic) == (UAV, SID)
    with (run / "raw.mcap").open("rb") as f:
        rd = make_reader(f)
        chans = {c.topic: c for c in rd.get_summary().channels.values()}
        schemas = rd.get_summary().schemas
        msgs = [(m.sequence, m.log_time, m.data) for _, ch, m in rd.iter_messages(topics=[topic])]
    ch = chans[topic]
