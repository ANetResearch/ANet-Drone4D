#!/usr/bin/env python3
"""受邀成员的 ZeroTier 授权与网络策略（AWR-05 §5.6.7、§7.11、ADR-183、Q-D3-15；AWR-17 §18.23.3 第 1 条；D3-AC-59）。

受邀成员经管理员批准加入内部工作区所在的 ZeroTier 网络后，网络层只放行三个服务：lab-web 与 bench-api（dmax
`$LAB_BIND:18660`，同一 nginx 入口）与 d3-registry（dmax `$REG_BIND:18670`）；dmax 上其余端口（ssh 与同机其他项目在 0.0.0.0
监听的服务）、其他成员与其余以太网类型一律丢弃。应用层另有逐请求鉴权（bench-api、lab-gateway、rerun-proxy、d3-registry-authz）。

策略按成员的 ZeroTier 地址（`ztsrc`/`ztdest`，由节点身份认证，成员无法伪造或隐瞒）生成，而不用标签：标签由发送方出示，
接收方未取得标签时 `tseq` 一类匹配不成立，策略若以"标签 = 受邀"为条件，隐瞒标签的成员会落入其余规则。生成片段的每条规则都含
`ztsrc <成员>` 或 `ztdest <成员>`，因此不改变非受邀成员之间的流量（`check` 子命令与测试逐项验证）。

子命令（不输出任何 API 令牌；`apply` 之外只读，不连接任何控制器）：

- `render --members F [--dmax-node N --dmax-ip IP --ports 18660,18670]`：由受邀成员表生成规则片段（含起止标记，可重复替换）。
  成员表 JSON：`{"members": [{"node": "<10 位十六进制>", "team": "<团队>", "expires": "YYYY-MM-DD"}]}`，已到期成员不生成放行
  规则，只保留丢弃规则（待管理员在控制器上取消授权）。
- `merge --rules F --fragment G`：把片段并入现有规则源（替换起止标记之间的旧片段；没有旧片段时放在最前，先于网络既有规则）。
- `check --rules F --members M [--scan S] [--out O]`：以规则子集求值器逐项求值可达矩阵（受邀成员 → dmax 各端口、受邀成员之间、
  内部成员不受影响、回程只来自三个服务端口）；`--scan` 为 `labctl.py scan` 的结果（dmax ZeroTier 地址上实际开放的端口），
  据此给出"受邀成员实际可达端口"= 开放端口 ∩ 放行端口。
- `plan --network NWID --members F [--rules-source F]`：打印管理员在 ZeroTier Central 执行的请求（成员授权、规则源替换），
  不发送；`apply … --yes`：由管理员执行（需环境变量 `ZT_CENTRAL_TOKEN`），对 `https://api.zerotier.com/api/v1` 先读取网络
  规则源并合并片段，再批准成员。本项目代理不执行 `apply`（用户 2026-10-18 决定：ZeroTier 网络配置与外部成员批准由用户执行）。

规则子集（ZeroTier 规则语言）：动作 `accept`、`drop`；匹配 `ztsrc`、`ztdest`、`ethertype`（ipv4、arp、ipv6 或数值）、`ipsrc`、
`ipdest`（CIDR）、`ipprotocol`（数值或 tcp、udp、icmp）、`sport`、`dport`（端口或 a-b），前缀 `not`，连接词 `and`、`or`
（自左向右）；`tag`、`cap` 定义块跳过。规则自上而下，首个匹配的动作生效，全部不匹配时丢弃。
"""

from __future__ import annotations

import argparse
import datetime as dt
import ipaddress
import json
import os
import re
import sys
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

BEGIN = "# >>> d3-invited (generated by tools/deploy/dmax/registry/zerotier/ztmember.py; do not edit by hand)"
END = "# <<< d3-invited"
DMAX_NODE = "49fa1aa631"          # dmax 的 ZeroTier 节点地址（zerotier-cli info，2026-10-19 核对）
DMAX_IP = "10.253.20.5"           # dmax 在内部工作区网络（chatchat-01，ebe7fbd445ade5dd）上的地址（lab.env LAB_BIND）
NETWORK = "ebe7fbd445ade5dd"
PORTS = (18660, 18670)            # lab-web 与 bench-api（同一 nginx 入口）、d3-registry
CENTRAL = "https://api.zerotier.com/api/v1"
ETHERTYPES = {"ipv4": 0x0800, "arp": 0x0806, "ipv6": 0x86DD}
PROTOCOLS = {"icmp": 1, "tcp": 6, "udp": 17}
_NODE = re.compile(r"^[0-9a-f]{10}$")


# ── 成员表与片段生成 ─────────────────────────────────────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Member:
    node: str
    team: str
    expires: str | None = None

    def expired(self, today: dt.date) -> bool:
        return self.expires is not None and dt.date.fromisoformat(self.expires) < today


def load_members(path: str | Path) -> list[Member]:
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    out = []
    for m in doc.get("members", []):
        node = str(m["node"]).lower()
        if not _NODE.match(node):
            raise ValueError(f"member node {node!r} is not a 10-digit hex ZeroTier address")
        if m.get("expires"):
            dt.date.fromisoformat(m["expires"])
        out.append(Member(node, str(m.get("team", "")), m.get("expires")))
    if len({m.node for m in out}) != len(out):
        raise ValueError("duplicate member node in members file")
    return out


def render(members: list[Member], *, dmax_node: str = DMAX_NODE, dmax_ip: str = DMAX_IP, ports: tuple[int, ...] = PORTS,
           today: dt.date | None = None) -> str:
    """受邀成员表 → 规则片段（起止标记之间；每条规则都含 ztsrc 或 ztdest 为该成员）。"""
    today = today or dt.datetime.now(dt.timezone.utc).date()  # noqa: UP017 -- 管理员与 dmax 宿主为 Python 3.10
    if not _NODE.match(dmax_node):
        raise ValueError(f"dmax node {dmax_node!r} is not a 10-digit hex ZeroTier address")
    ipaddress.IPv4Address(dmax_ip)
    lines = [BEGIN,
             f"# 受邀成员只可访问 dmax {dmax_ip} 的 TCP {', '.join(map(str, ports))}（lab-web 与 bench-api、d3-registry）；其余流量丢弃。",
             f"# 成员 {len(members)} 个；生成于 {today.isoformat()}（UTC）。"]
    for m in sorted(members, key=lambda x: (x.team, x.node)):
        exp = m.expired(today)
        lines.append(f"# {m.node} team={m.team or '-'} expires={m.expires or '-'}{' EXPIRED: deauthorize on the controller' if exp else ''}")
        if not exp:
            lines += [f"accept ztsrc {m.node} and ztdest {dmax_node} and ethertype ipv4 and ipdest {dmax_ip}/32 and ipprotocol 6 and dport {p};"
                      for p in ports]
            lines += [f"accept ztsrc {dmax_node} and ztdest {m.node} and ethertype ipv4 and ipsrc {dmax_ip}/32 and ipprotocol 6 and sport {p};"
                      for p in ports]
            lines.append(f"accept ztsrc {m.node} and ethertype arp;")
            lines.append(f"accept ztdest {m.node} and ethertype arp;")
        lines.append(f"drop ztsrc {m.node};")
        lines.append(f"drop ztdest {m.node};")
    lines.append(END)
    return "\n".join(lines) + "\n"


def merge(rules_source: str, fragment: str) -> str:
    """替换现有规则源中起止标记之间的旧片段；没有旧片段时把片段放在最前（先于网络既有规则）。"""
    src = rules_source or ""
    i, j = src.find(BEGIN), src.find(END)
    if i >= 0 and j > i:
        tail = src[j + len(END):]
        return src[:i] + fragment.rstrip("\n") + (tail if tail.startswith("\n") else "\n" + tail)
    if (i >= 0) != (j >= 0):
        raise ValueError("rules source has an unmatched d3-invited marker")
    return fragment + ("\n" + src if src.strip() else "accept;\n")


# ── 规则子集求值 ─────────────────────────────────────────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Cond:
    key: str
    value: Any
    negate: bool = False
    or_: bool = False


@dataclass
class Rule:
    action: str
    conds: list[Cond] = field(default_factory=list)
    text: str = ""


def _strip_comments(src: str) -> str:
    return "\n".join(ln.split("#", 1)[0] for ln in src.splitlines())


def _port_range(v: str) -> tuple[int, int]:
    a, _, b = v.partition("-")
    lo, hi = int(a), int(b or a)
    if not 0 <= lo <= hi <= 65535:
        raise ValueError(f"bad port range {v!r}")
    return lo, hi


def _value(key: str, v: str) -> Any:
    if key in ("ztsrc", "ztdest"):
        if not _NODE.match(v.lower()):
            raise ValueError(f"{key} {v!r} is not a ZeroTier address")
        return v.lower()
    if key == "ethertype":
        return ETHERTYPES[v] if v in ETHERTYPES else int(v, 0)
    if key in ("ipsrc", "ipdest"):
        return ipaddress.ip_network(v, strict=False)
    if key == "ipprotocol":
        return PROTOCOLS[v] if v in PROTOCOLS else int(v, 0)
    if key in ("sport", "dport"):
        return _port_range(v)
    raise ValueError(f"unsupported match {key!r} (rule subset: ztsrc ztdest ethertype ipsrc ipdest ipprotocol sport dport)")


def parse_rules(src: str) -> list[Rule]:
    """规则源 → 规则表（子集，见模块说明）。`tag`/`cap` 定义块跳过；不支持的匹配或动作报 ValueError。"""
    rules = []
    for stmt in _strip_comments(src).split(";"):
        toks = stmt.split()
        if not toks:
            continue
        if toks[0] in ("tag", "cap"):
            continue
        if toks[0] not in ("accept", "drop"):
            raise ValueError(f"unsupported action {toks[0]!r} in {stmt.strip()!r}")
        conds, i, neg, or_ = [], 1, False, False
        while i < len(toks):
            t = toks[i]
            if t == "not":
                neg, i = not neg, i + 1
                continue
            if t in ("and", "or"):
                if not conds:
                    raise ValueError(f"leading {t!r} in {stmt.strip()!r}")
                or_, i = t == "or", i + 1
                continue
            if i + 1 >= len(toks):
                raise ValueError(f"match {t!r} has no value in {stmt.strip()!r}")
            conds.append(Cond(t, _value(t, toks[i + 1]), neg, or_))
            neg, or_, i = False, False, i + 2
        rules.append(Rule(toks[0], conds, " ".join(toks)))
    return rules


@dataclass(frozen=True)
class Flow:
    """一帧的匹配要素；非 IP 帧的 IP 与端口字段为 None（端口与地址匹配不成立）。"""
    src: str
    dst: str
    ethertype: int = ETHERTYPES["ipv4"]
    ipsrc: str | None = None
    ipdest: str | None = None
    proto: int | None = 6
    sport: int | None = None
    dport: int | None = None


def _match(c: Cond, f: Flow) -> bool:
    k, v = c.key, c.value
    if k == "ztsrc":
        r = f.src == v
    elif k == "ztdest":
        r = f.dst == v
    elif k == "ethertype":
        r = f.ethertype == v
    elif k in ("ipsrc", "ipdest"):
        a = f.ipsrc if k == "ipsrc" else f.ipdest
        r = a is not None and ipaddress.ip_address(a) in v
    elif k == "ipprotocol":
        r = f.proto is not None and f.ethertype in (ETHERTYPES["ipv4"], ETHERTYPES["ipv6"]) and f.proto == v
    else:
        p = f.sport if k == "sport" else f.dport
        r = p is not None and v[0] <= p <= v[1]
    return r != c.negate


def evaluate(rules: list[Rule], f: Flow) -> tuple[str, int | None]:
    """→ (动作, 命中规则序号)；全部不匹配时 ("drop", None)（ZeroTier 规则表末尾的隐式丢弃）。"""
    for i, r in enumerate(rules):
        ok = True
        for j, c in enumerate(r.conds):
            m = _match(c, f)
            ok = m if j == 0 else ((ok or m) if c.or_ else (ok and m))
        if ok:
            return r.action, i
    return "drop", None


def strip_fragment(rules_source: str) -> str:
    """去掉起止标记之间的片段（网络既有规则，作为"非受邀流量不变"的对照）。"""
    i, j = rules_source.find(BEGIN), rules_source.find(END)
    return rules_source[:i] + rules_source[j + len(END):] if i >= 0 and j > i else rules_source


def check(rules_source: str, members: list[Member], *, dmax_node: str = DMAX_NODE, dmax_ip: str = DMAX_IP, ports: tuple[int, ...] = PORTS,
          open_ports: list[int] | None = None, internal_node: str = "0000000001", internal_ip: str = "10.253.20.3",
          today: dt.date | None = None) -> dict:
    """可达矩阵：每个未到期受邀成员对 dmax 的放行端口与开放端口、受邀成员之间、回程端口；内部成员的流量与去掉片段后的
    既有规则逐项相同（片段不改变非受邀流量）。"""
    today = today or dt.datetime.now(dt.timezone.utc).date()  # noqa: UP017 -- 管理员与 dmax 宿主为 Python 3.10
    rules = parse_rules(rules_source)
    base = parse_rules(strip_fragment(rules_source))
    probe = sorted(set(open_ports or []) | set(ports) | {22, 80, 443, 8000, 8765, 9993, 18650, 18651, 18652, 18653, 18654, 19000})
    items: list[dict] = []

    def add(name: str, f: Flow, want: str) -> None:
        act, idx = evaluate(rules, f)
        items.append({"check": name, "want": want, "got": act, "rule": idx, "ok": act == want})

    live = [m for m in members if not m.expired(today)]
    for k, m in enumerate(members):
        mip = f"10.253.20.{200 + k}"
        allowed = {p for p in ports} if m in live else set()
        for p in probe:
            add(f"{m.node} -> dmax tcp/{p}", Flow(m.node, dmax_node, ipsrc=mip, ipdest=dmax_ip, sport=40000, dport=p),
                "accept" if p in allowed else "drop")
            add(f"dmax tcp/{p} -> {m.node} (reply)", Flow(dmax_node, m.node, ipsrc=dmax_ip, ipdest=mip, sport=p, dport=40000),
                "accept" if p in allowed else "drop")
        add(f"{m.node} -> dmax udp/18660", Flow(m.node, dmax_node, ipsrc=mip, ipdest=dmax_ip, proto=17, sport=40000, dport=18660), "drop")
        add(f"{m.node} -> dmax ipv6 tcp/18660", Flow(m.node, dmax_node, ethertype=ETHERTYPES["ipv6"], proto=6, sport=40000, dport=18660), "drop")
        add(f"{m.node} -> dmax icmp", Flow(m.node, dmax_node, ipsrc=mip, ipdest=dmax_ip, proto=1), "drop")
        add(f"{m.node} -> other dmax address tcp/18660", Flow(m.node, dmax_node, ipsrc=mip, ipdest="10.253.20.99", sport=40000, dport=18660),
            "drop")
        add(f"{m.node} -> internal member tcp/22", Flow(m.node, internal_node, ipsrc=mip, ipdest=internal_ip, dport=22), "drop")
        add(f"internal member -> {m.node} tcp/22", Flow(internal_node, m.node, ipsrc=internal_ip, ipdest=mip, dport=22), "drop")
        add(f"{m.node} arp", Flow(m.node, dmax_node, ethertype=ETHERTYPES["arp"], proto=None), "accept" if m in live else "drop")
        for n in members:
            if n.node != m.node:
                add(f"{m.node} -> {n.node} tcp/18660", Flow(m.node, n.node, ipsrc=mip, ipdest="10.253.20.250", dport=18660), "drop")
    others = [Flow(internal_node, dmax_node, ipsrc=internal_ip, ipdest=dmax_ip, sport=40000, dport=p) for p in probe]
    others += [Flow(dmax_node, internal_node, ipsrc=dmax_ip, ipdest=internal_ip, sport=p, dport=40000) for p in probe]
    others += [Flow(internal_node, dmax_node, ethertype=ETHERTYPES["arp"], proto=None),
               Flow(internal_node, dmax_node, ethertype=ETHERTYPES["ipv6"], proto=6, sport=40000, dport=22),
               Flow(internal_node, "0000000002", ipsrc=internal_ip, ipdest="10.253.20.4", proto=17, sport=5353, dport=5353)]
    for f in others:                                          # 片段不改变非受邀成员的流量：与既有规则的结果相同
        add(f"non-invited {f.src}->{f.dst} eth={f.ethertype:#06x} proto={f.proto} {f.sport}->{f.dport} (unchanged)", f, evaluate(base, f)[0])
    reach = {m.node: sorted(p for p in (open_ports or []) if evaluate(rules, Flow(m.node, dmax_node, ipsrc="10.253.20.200", ipdest=dmax_ip,
                                                                                    sport=40000, dport=p))[0] == "accept") for m in members}
    return {"ok": all(i["ok"] for i in items), "n_checks": len(items), "n_failed": sum(not i["ok"] for i in items),
            "open_ports": sorted(open_ports or []), "invited_reachable_open_ports": reach, "checks": items}


# ── ZeroTier Central（管理员执行） ────────────────────────────────────────────────────────────────────────────────────

def _member_body(m: Member, today: dt.date) -> dict:
    """成员设置：授权（到期即取消）与说明；不改成员的地址分配与标签。"""
    return {"name": f"d3-invited {m.team}", "description": f"D3 invited member, team {m.team}, expires {m.expires or '-'}",
            "config": {"authorized": not m.expired(today)}}


def plan(network: str, members: list[Member], rules_source: str | None, today: dt.date | None = None) -> dict:
    today = today or dt.datetime.now(dt.timezone.utc).date()  # noqa: UP017 -- 管理员与 dmax 宿主为 Python 3.10
    frag = render(members, today=today)
    reqs = []
    if rules_source is not None:
        reqs.append({"method": "POST", "url": f"{CENTRAL}/network/{network}", "body": {"rulesSource": merge(rules_source, frag)}})
    else:
        reqs.append({"method": "GET", "url": f"{CENTRAL}/network/{network}", "then": "merge config.rulesSource with the fragment, POST rulesSource"})
    reqs += [{"method": "POST", "url": f"{CENTRAL}/network/{network}/member/{m.node}", "body": _member_body(m, today)} for m in members]
    return {"network": network, "fragment": frag, "requests": reqs, "auth": "Authorization: token $ZT_CENTRAL_TOKEN (not printed)"}


def _central(method: str, url: str, token: str, body: dict | None = None) -> dict:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers={"Authorization": f"token {token}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read() or b"{}")


def apply(network: str, members: list[Member], token: str, *, base: str = CENTRAL, today: dt.date | None = None) -> dict:
    """管理员执行：读取网络规则源 → 合并片段 → 写回；逐个成员设置授权（到期成员取消授权）。返回摘要（不含令牌）。"""
    today = today or dt.datetime.now(dt.timezone.utc).date()  # noqa: UP017 -- 管理员与 dmax 宿主为 Python 3.10
    net = _central("GET", f"{base}/network/{network}", token)
    src = (net.get("rulesSource") or (net.get("config") or {}).get("rulesSource") or "")
    merged = merge(src, render(members, today=today))
    parse_rules(merged.split(END, 1)[0] + END)                # 片段自检（既有规则不在子集内时不求值）
    _central("POST", f"{base}/network/{network}", token, {"rulesSource": merged})
    done = []
    for m in members:
        auth = not m.expired(today)
        _central("POST", f"{base}/network/{network}/member/{m.node}", token, _member_body(m, today))
        done.append({"node": m.node, "team": m.team, "authorized": auth})
    return {"network": network, "rules_bytes": len(merged.encode()), "members": done}


# ── 命令行 ───────────────────────────────────────────────────────────────────────────────────────────────────────────

def _ports(s: str) -> tuple[int, ...]:
    return tuple(int(x) for x in s.split(",") if x.strip())


def _write(out: str | None, obj: Any) -> None:
    text = obj if isinstance(obj, str) else json.dumps(obj, ensure_ascii=False, indent=1) + "\n"
    if out:
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        Path(out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="ztmember.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("render", "check", "plan", "apply"):
        s = sub.add_parser(name)
        s.add_argument("--members", required=True)
        s.add_argument("--dmax-node", default=DMAX_NODE)
        s.add_argument("--dmax-ip", default=DMAX_IP)
        s.add_argument("--ports", type=_ports, default=PORTS)
        s.add_argument("--out")
        if name == "check":
            s.add_argument("--rules", help="rules source to evaluate (default: the rendered fragment followed by 'accept;')")
            s.add_argument("--scan", help="labctl.py scan JSON of the dmax ZeroTier address (open ports)")
        if name in ("plan", "apply"):
            s.add_argument("--network", default=NETWORK)
        if name == "plan":
            s.add_argument("--rules-source", help="current network rulesSource (text file) to merge into")
        if name == "apply":
            s.add_argument("--yes", action="store_true", help="required: the administrator confirms the change")
    m = sub.add_parser("merge")
    m.add_argument("--rules", required=True)
    m.add_argument("--fragment", required=True)
    m.add_argument("--out")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "merge":
            _write(a.out, merge(Path(a.rules).read_text(encoding="utf-8"), Path(a.fragment).read_text(encoding="utf-8")))
            return 0
        members = load_members(a.members)
        if a.cmd == "render":
            _write(a.out, render(members, dmax_node=a.dmax_node, dmax_ip=a.dmax_ip, ports=a.ports))
            return 0
        if a.cmd == "check":
            src = Path(a.rules).read_text(encoding="utf-8") if a.rules else render(members, dmax_node=a.dmax_node, dmax_ip=a.dmax_ip,
                                                                                        ports=a.ports) + "accept;\n"
            open_ports = None
            if a.scan:
                scan = json.loads(Path(a.scan).read_text(encoding="utf-8"))
                open_ports = sorted(int(p) for p, st in (scan.get("ports") or {}).items() if st == "open")
            rep = check(src, members, dmax_node=a.dmax_node, dmax_ip=a.dmax_ip, ports=a.ports, open_ports=open_ports)
            rep["schema"] = "awr.d3.zt_policy_check.v1"
            _write(a.out, rep)
            return 0 if rep["ok"] else 1
        if a.cmd == "plan":
            rs = Path(a.rules_source).read_text(encoding="utf-8") if a.rules_source else None
            _write(a.out, plan(a.network, members, rs))
            return 0
        if not a.yes:
            print("apply changes the ZeroTier network; rerun with --yes as the administrator", file=sys.stderr)
            return 2
        token = os.environ.get("ZT_CENTRAL_TOKEN", "")
        if not token:
            print("ZT_CENTRAL_TOKEN is not set", file=sys.stderr)
            return 2
        _write(a.out, apply(a.network, members, token))
        return 0
    except (ValueError, KeyError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
