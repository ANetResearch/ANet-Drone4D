// ---------------------------------------------------------------- main
async function main() {
  const check = process.argv.includes('--check')
  const layouts = readJson('rt/layouts.json')
  const enums = readJson('rt/enums.json')
  const errs = checkLayouts(layouts, enums)
  if (errs.length) {
    console.error('contract error: ' + errs.join('; '))
    process.exit(2)
  }
  const c = {
    version: readJson('package.json').version,
    layouts, enums,
    commands: readJson('rt/commands.json'),
    reasons: readJson('rt/reasons.json'),
    topics: readJson('rt/topics.json'),
    units: readJson('rt/units.json'),
    safety: readJson('rt/safety_codes.json'),
    presetsText: fs.readFileSync(path.join(CONTRACTS, 'env', 'presets.json'), 'utf8'),
    layoutId: layoutId(layouts),
    schemaHash: Object.fromEntries(layouts.schemas.map((s) => [s.schemaName, schemaHash(s)])),
  }
  const files = {
    'index.ts': genIndex(),
    'layouts.ts': genLayouts(c),
    'frame.ts': genFrame(c),
    'time.ts': genTime(c),
    'enums.ts': genEnums(c),
    'reasons.ts': genReasons(c),
    'commands.ts': genCommands(c),
    'topics.ts': genTopics(c),
    'units.ts': genUnits(c),
    'presets.ts': genPresets(c),
    'safetyCodes.ts': genSafety(c),
    'types.ts': await genTypes(),
  }
  let diffs = 0
  for (const [name, text] of Object.entries(files).sort()) {
    const p = path.join(OUT, name)
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null
    if (cur !== text) {
      diffs++
      if (check) console.log(`out of date: ${path.relative(ROOT, p)}`)
      else {
        fs.mkdirSync(OUT, { recursive: true })
        fs.writeFileSync(p, text)
        console.log(`wrote ${path.relative(ROOT, p)}`)
      }
    }
  }
  for (const f of fs.existsSync(OUT) ? fs.readdirSync(OUT).sort() : []) {
    if (!(f in files)) {
      diffs++
      if (check) console.log(`unexpected file (not generated): ${path.relative(ROOT, path.join(OUT, f))}`)
      else {
        fs.rmSync(path.join(OUT, f))
        console.log(`removed stale ${f}`)
      }
    }
  }
  if (check && diffs) {
    console.error(`gen.mjs --check: ${diffs} file(s) differ; run node tools/contracts/gen.mjs`)
    process.exit(1)
  }
  console.log(`gen.mjs: ${diffs ? `${diffs} file(s) updated` : 'up to date'} (layout_id 0x${c.layoutId.toString(16).toUpperCase().padStart(8, '0')}, contracts ${c.version})`)
}

await main()
