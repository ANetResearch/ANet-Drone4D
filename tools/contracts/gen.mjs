// ---------------------------------------------------------------- types.ts via json-schema-to-typescript over one bundle
function schemaFiles() {
  const out = []
  const walk = (d) => {
    for (const f of fs.readdirSync(d).sort()) {
      const p = path.join(d, f)
      const rel = path.relative(CONTRACTS, p)
      if (fs.statSync(p).isDirectory()) {
        if (!['gen', 'fixtures', 'golden'].includes(rel.split(path.sep)[0])) walk(p)
      } else if (f.endsWith('.schema.json')) out.push(p)
    }
  }
  walk(CONTRACTS)
  return out
}

function bundleSchemas() {
  const docs = new Map()
  for (const p of schemaFiles()) {
    const d = JSON.parse(fs.readFileSync(p, 'utf8'))
    docs.set(d.$id, { p, d })
  }
  const pas = (s) => s.split(/[-_./@ $]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
  const base = new Map()
  const used = new Set()
  for (const [id, { p }] of [...docs.entries()].sort()) {
    const dom = id.split('/')[3]
    let b = pas(path.basename(p, '.schema.json'))
    if (used.has(b) || ['Command', 'Event', 'Detail', 'Common'].includes(b)) b = pas(dom) + b
    used.add(b)
    base.set(id, b)
  }
  const defs = {}
  const nameOf = (id, frag) => {
    const segs = frag.split('/').filter((s) => s && s !== '$defs')
    return base.get(id) + segs.map(pas).join('')
  }
  const resolveId = (from, ref) => {
    const [b, frag = ''] = ref.split('#')
    if (!b) return [from, frag]
    const parts = from.split('/').slice(0, -1)
    for (const seg of b.split('/')) {
      if (seg === '..') parts.pop()
      else if (seg && seg !== '.') parts.push(seg)
    }
    return [parts.join('/'), frag]
  }
  const pending = []
  const hoist = (id, frag) => {
    const n = nameOf(id, frag)
    if (!(n in defs)) {
      defs[n] = null
      pending.push([id, frag, n])
    }
    return n
  }
  const nodeAt = (id, frag) => {
    let d = docs.get(id).d
    for (const seg of frag.split('/').filter(Boolean)) d = d[seg.replace(/~1/g, '/').replace(/~0/g, '~')]
    return d
  }
  const rewrite = (id, node) => {
    if (Array.isArray(node)) return node.map((x) => rewrite(id, x))
    if (!node || typeof node !== 'object') return node
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref') {
        const [tid, frag] = resolveId(id, v)
        out.$ref = '#/definitions/' + hoist(tid, frag)
      } else if (k === '$defs' || k === '$id' || k === '$schema' || k === 'if' || k === 'then' || k === 'else' || k === 'not') {
        continue
      } else if (k === 'prefixItems') {
        continue
      } else out[k] = rewrite(id, v)
    }
    return out
  }
  for (const id of [...docs.keys()].sort()) {
    hoist(id, '')
    for (const k of Object.keys(docs.get(id).d.$defs ?? {})) hoist(id, '/$defs/' + k)
  }
  while (pending.length) {
    const [id, frag, n] = pending.shift()
    const node = rewrite(id, nodeAt(id, frag))
    const title = node.title
    node.title = n
    if (title) node.description = title + (node.description ? '. ' + node.description : '')
    defs[n] = node
  }
  const sorted = Object.fromEntries(Object.keys(defs).sort().map((k) => [k, defs[k]]))
  return { $schema: 'http://json-schema.org/draft-07/schema#', title: 'AwrContracts', type: 'object', additionalProperties: false, properties: {}, definitions: sorted }
}

async function genTypes() {
  const { compile } = await import(path.join(ROOT, 'node_modules', 'json-schema-to-typescript', 'dist', 'src', 'index.js'))
  const ts = await compile(bundleSchemas(), 'AwrContracts', {
    bannerComment: BANNER.trim() + '\n// Types for every JSON Schema under packages/contracts (json-schema-to-typescript 16, one bundled schema).',
    additionalProperties: false,
    unreachableDefinitions: true,
    declareExternallyReferenced: true,
    maxItems: -1,
    format: true,
    strictIndexSignatures: false,
    style: { semi: false, singleQuote: true, printWidth: 140 },
  })
  return ts
}

