# ---------------------------------------------------------------- enums
def gen_enums(c: dict) -> str:
    E = c["enums"]
    out = [HDR.format(doc="Enumerations from packages/contracts/rt/enums.json (awr.enums.v1)."),
           "from __future__ import annotations\n\nfrom enum import IntEnum, IntFlag\n\n"]
    for name in E:
        if not name[0].isupper():
            continue
        if L.is_simple_enum(E, name):
            base = "IntFlag" if name in L.FLAG_ENUMS else "IntEnum"
            members = L.enum_members(E, name)
            out.append(f"\nclass {name}({base}):\n")
            for idn, v, _ in members:
                out.append(f"    {idn} = {v}\n")
            names = {v: w for _, v, w in members}
            out.append(f"\n\n{L.ident(name)}_NAMES: dict[int, str] = {pylit(names)}\n")
            out.append(f"{L.ident(name)}_BY_NAME: dict[str, int] = {pylit({w: v for v, w in names.items()})}\n\n")
    fs = [x for x in E["FlightState"]]
    sub = {k: v for k, v in E["FlightSub"].items()}
    out.append("\n# FlightSub: 3-bit sub-mode names per FlightState (None = reserved slot)\n")
    out.append("FLIGHT_SUB: dict[int, tuple[str | None, ...]] = {\n")
    for i, n in enumerate(fs):
        out.append(f"    {i}: {pylit(sub[n])},\n")
    out.append("}\n\n")
    out.append("SEVERITY: dict[int, int] = {" + ", ".join(f"FlightState.{k}: {v}" for k, v in E["Severity"].items()) + "}\n\n")
    out.append("JOB_STATE: dict[str, tuple[str, ...]] = {" + ", ".join(f"{json.dumps(k)}: {pylit(v)}" for k, v in E["JobState"].items()) + "}\n\n")
    out.append(
        "\ndef sub_name(fs: int, sub: int) -> str | None:\n"
        "    names = FLIGHT_SUB.get(fs, ())\n"
        "    return names[sub] if 0 <= sub < len(names) else None\n\n\n"
        "def sub_value(fs: int, name: str) -> int:\n"
        "    return FLIGHT_SUB[fs].index(name)\n\n\n"
        "def time_state(state_byte: int) -> TimeState:\n"
        '    """Low 4 bits of TIME.state / clock_state; bit7 (REPLAY) is masked (AWR-03 §5.2 rule 6)."""\n'
        "    return TimeState(state_byte & TimeFlags.STATE_MASK)\n\n\n"
        "def time_is_replay(state_byte: int) -> bool:\n"
        "    return bool(state_byte & TimeFlags.REPLAY)\n\n\n"
        "def time_advances(state_byte: int) -> bool:\n"
        '    """SimClockView advances only in PLAYING and LIVE; every other state freezes."""\n'
        "    return time_state(state_byte) in (TimeState.PLAYING, TimeState.LIVE)\n\n\n"
        "def red_highlight(fs: int, flags: int) -> bool:\n"
        '    """Swarm-wide red highlight: CORRECTING <= fs <= CRASHED and fs != LANDED, or ALERT (g04 §5.4)."""\n'
        "    return (FlightState.CORRECTING <= fs <= FlightState.CRASHED and fs != FlightState.LANDED) or bool(flags & FlightFlags.ALERT)\n"
    )
    return "".join(out)


# ---------------------------------------------------------------- layouts
def gen_layouts(c: dict) -> str:
    Ls = c["layouts"]["schemas"]
    out = [HDR.format(doc="Binary layouts from packages/contracts/rt/layouts.json: numpy dtypes, offsets, bit fields (AWR-17 §10.3, §10.4)."),
           "from __future__ import annotations\n\nimport numpy as np\n\n",
           f"LAYOUT_ID = 0x{c['layout_id']:08X}\n",
           "SCHEMA_HASH: dict[str, str] = {\n" + "".join(f'    "{k}": "{v}",\n' for k, v in c["schema_hash"].items()) + "}\n\n"]
    for sch in Ls:
        cn = L.const_name(sch["schemaName"])
        fields = sch["fields"]
        names = [f["n"] for f in fields]
        fmts = [(L.NP_FMT[f["t"]], f.get("c", 1)) for f in fields]
        fmt_lit = ", ".join(f'"{t}"' if cnt == 1 else f'("{t}", {cnt})' for t, cnt in fmts)
        out.append(f"# {sch['schemaName']} ({sch['size']} B): {sch.get('doc', '')}\n")
        out.append(f"{cn} = np.dtype({{\n    \"names\": {json.dumps(names)},\n"
                   f"    \"formats\": [{fmt_lit}],\n"
                   f"    \"offsets\": {json.dumps([f['o'] for f in fields])},\n"
                   f"    \"itemsize\": {sch['size']},\n}})\n")
        out.append(f"assert {cn}.itemsize == {sch['size']}\n")
        out.append(f"{cn}_OFFSETS: dict[str, int] = {pylit({f['n']: f['o'] for f in fields})}\n")
        scales = {f["n"]: f["scale"] for f in fields if "scale" in f}
        if scales:
            out.append(f"{cn}_SCALE: dict[str, float] = {pylit(scales)}\n")
        nones = {f["n"]: f["none"] for f in fields if "none" in f}
        if nones:
            out.append(f"{cn}_NONE: dict[str, int] = {pylit(nones)}\n")
        bits = {f["n"]: {k: tuple(v) for k, v in f["bits"].items()} for f in fields if "bits" in f}
        if bits:
            out.append(f"{cn}_BITS: dict[str, dict[str, tuple]] = {pylit(bits)}\n")
        consts = {f["n"]: f["const"] for f in fields if "const" in f}
        if consts:
            out.append(f"{cn}_CONST: dict[str, int] = {pylit(consts)}\n")
        out.append("\n")
    out.append("DTYPES: dict[str, np.dtype] = {\n" + "".join(f'    "{s["schemaName"]}": {L.const_name(s["schemaName"])},\n' for s in Ls) + "}\n")
    out.append("SIZES: dict[str, int] = {\n" + "".join(f'    "{s["schemaName"]}": {s["size"]},\n' for s in Ls) + "}\n")
    out.append(
        "\n\ndef pack_bits(spec: dict[str, tuple], **values: int) -> int:\n"
        '    """Pack named bit fields (spec from *_BITS[field]) into an integer."""\n'
        "    v = 0\n"
        "    for name, x in values.items():\n"
        "        start, width = spec[name][0], spec[name][1]\n"
        "        v |= (int(x) & ((1 << width) - 1)) << start\n"
        "    return v\n\n\n"
        "def unpack_bits(spec: dict[str, tuple], value: int) -> dict[str, int]:\n"
        "    return {name: (int(value) >> s[0]) & ((1 << s[1]) - 1) for name, s in spec.items()}\n\n\n"
        "def pack_fs(state: int, sub: int = 0) -> int:\n"
        '    """flight_state byte: bit0-4 FlightState, bit5-7 sub-mode."""\n'
        "    return (state & 0x1F) | ((sub & 7) << 5)\n\n\n"
        "def unpack_fs(b: int) -> tuple[int, int]:\n"
        "    return b & 0x1F, (b >> 5) & 7\n\n\n"
        "def pack_ctrl(owner: int, locked: bool, native: int, pose: int) -> int:\n"
        '    """ctrl byte: bit0-2 owner, bit3 locked, bit4-5 native, bit6-7 pose_src."""\n'
        "    return (owner & 7) | (int(locked) << 3) | ((native & 3) << 4) | ((pose & 3) << 6)\n\n\n"
        "def unpack_ctrl(b: int) -> tuple[int, bool, int, int]:\n"
        "    return b & 7, bool(b & 8), (b >> 4) & 3, (b >> 6) & 3\n\n\n"
        "def lite_from_full(full: np.ndarray, out: np.ndarray | None = None) -> np.ndarray:\n"
        '    """Quantise Full64 rows into Lite32 rows (q x32767, vel x100, both rounded and clamped to +-32767)."""\n'
        "    if out is None:\n        out = np.zeros(len(full), SWARM_LITE32)\n"
        "    out[\"agent_no\"] = full[\"agent_no\"]\n"
        "    out[\"flight_state\"] = full[\"flight_state\"]\n"
        "    out[\"battery_pct\"] = full[\"battery_pct\"]\n"
        "    out[\"pos\"] = full[\"pos\"]\n"
        "    out[\"q_snorm\"] = np.clip(np.rint(full[\"q\"].astype(np.float64) * 32767.0), -32767, 32767).astype(np.int16)\n"
        "    out[\"vel_cms\"] = np.clip(np.rint(full[\"vel\"].astype(np.float64) * 100.0), -32767, 32767).astype(np.int16)\n"
        "    out[\"flags\"] = full[\"flags\"]\n"
        "    out[\"ctrl\"] = full[\"ctrl\"]\n"
        "    return out\n"
    )
    return "".join(out)


# ---------------------------------------------------------------- frame (struct formats and codecs)
def gen_frame(c: dict) -> str:
    S = {s["schemaName"]: s for s in c["layouts"]["schemas"]}
    out = [HDR.format(doc="awr.rt.v1 frame codecs: struct formats, opcodes, flag bits, TIME and BATCH helpers (AWR-17 §6.4)."),
           "from __future__ import annotations\n\nimport struct\nfrom collections.abc import Iterator\nfrom typing import NamedTuple\n\n"
           "from .enums import TimeFlags, TimeState\n\n"]
    out.append("STRUCT_FORMATS: dict[str, str] = {\n" + "".join(f'    "{n}": "{L.struct_format(s)}",\n' for n, s in S.items()) + "}\n")
    out.append("STRUCTS: dict[str, struct.Struct] = {k: struct.Struct(v) for k, v in STRUCT_FORMATS.items()}\n\n")
    named = [("FRAME_HDR", "awr.rt.BatchHeader.v1"), ("REC_HDR", "awr.rt.RecordHeader.v1"), ("TIME", "awr.rt.Time.v1"),
             ("CLIENT_DATA_HDR", "awr.rt.ClientDataHeader.v1"), ("SETPOINT32", "awr.bus.Setpoint32.v1"), ("VEL_SETPOINT16", "awr.VelSetpoint16.v1"),
             ("REC_PREFIX8", "awr.rec.RecPrefix8.v1"), ("AWRT_HDR", "awr.fixture.AwrtHeader.v1"), ("AWRT_REC", "awr.fixture.AwrtRecord.v1"),
             ("BLOB_HDR", "awr.blob.Header.v1"), ("SWARM_BLOCK_HDR", "awr.SwarmLite32Block.v1"), ("AWRV_HDR", "awr.env.AwrvHeader.v1"),
             ("AWSL_HDR", "awr.env.AwslHeader.v1"), ("AWTR_HDR", "awr.recon.AwtrHeader.v1"), ("HEARTBEAT16", "awr.ipc.Heartbeat16.v1")]
    for n, sn in named:
        out.append(f'{n} = STRUCTS["{sn}"]\n')
    out.append('SETPOINT_BUS = struct.Struct("<HBBIq")  # header part of awr.bus.Setpoint32.v1 (M11 §6.3.9)\n')
    out.append('assert SETPOINT_BUS.size + VEL_SETPOINT16.size == SETPOINT32.size\n\n')
    bh = S["awr.rt.BatchHeader.v1"]["fields"]
    rh = S["awr.rt.RecordHeader.v1"]["fields"]
    cd = S["awr.rt.ClientDataHeader.v1"]["fields"]
    tm = S["awr.rt.Time.v1"]["fields"]
    def const_of(fields, n):
        return next(f["const"] for f in fields if f["n"] == n)
    out.append(f"OP_TIME = 0x{const_of(tm, 'op'):02X}\nOP_BATCH = 0x{const_of(bh, 'op'):02X}\nOP_CLIENT_DATA = 0x{const_of(cd, 'op'):02X}\n\n")
    for fields, prefix, fname in [(bh, "BATCH_", "flags"), (rh, "RF_", "rflags"), (cd, "CD_", "flags")]:
        f = next(x for x in fields if x["n"] == fname)
        for bn, spec in f["bits"].items():
            out.append(f"{prefix}{bn.upper()} = 0x{1 << spec[0]:02X}\n")
        out.append("\n")
    enc = c["enums"]["Encoding"]
    for i, e in enumerate(enc):
        out.append(f"ENC_{e.upper()} = {i}\n")
    out.append(
        "\nTIME_REPLAY_BIT = int(TimeFlags.REPLAY)\n\n\n"
        "def pad8(n: int) -> int:\n    return (n + 7) & ~7\n\n\n"
        "class TimeFrame(NamedTuple):\n"
        "    state: int\n    replay: bool\n    epoch: int\n    rate: float\n    t_sim_ns: int\n    t_srv_ns: int\n\n\n"
        "def encode_time(state: int, epoch: int, rate: float, t_sim_ns: int, t_srv_ns: int, replay: bool = False) -> bytes:\n"
        "    b = (int(state) & 0x0F) | (TIME_REPLAY_BIT if replay else 0)\n"
        "    return TIME.pack(OP_TIME, b, epoch & 0xFFFF, rate, t_sim_ns, t_srv_ns)\n\n\n"
        "def decode_time(buf: bytes | memoryview, off: int = 0) -> TimeFrame:\n"
        "    op, st, epoch, rate, t_sim, t_srv = TIME.unpack_from(buf, off)\n"
        "    if op != OP_TIME:\n        raise ValueError(f\"not a TIME frame: op=0x{op:02x}\")\n"
        "    return TimeFrame(st & 0x0F, bool(st & TIME_REPLAY_BIT), epoch, rate, t_sim, t_srv)\n\n\n"
        "def time_advances(frame: TimeFrame) -> bool:\n"
        "    return frame.state in (TimeState.PLAYING, TimeState.LIVE)\n\n\n"
        "class BatchHeader(NamedTuple):\n"
        "    flags: int\n    epoch: int\n    frame_seq: int\n    t_sim_ns: int\n\n\n"
        "class Record(NamedTuple):\n"
        "    channel_id: int\n    encoding: int\n    rflags: int\n    length: int\n    seq: int\n    dt_us: int\n    payload_off: int\n\n\n"
        "def decode_batch_header(buf: bytes | memoryview) -> BatchHeader:\n"
        "    op, flags, epoch, frame_seq, t_sim = FRAME_HDR.unpack_from(buf, 0)\n"
        "    if op != OP_BATCH:\n        raise ValueError(f\"not a BATCH frame: op=0x{op:02x}\")\n"
        "    return BatchHeader(flags, epoch, frame_seq, t_sim)\n\n\n"
        "def iter_records(buf: bytes | memoryview, off: int = 16) -> Iterator[Record]:\n"
        '    """Walk BATCH records; unknown encodings are yielded too (callers skip them). Raises on truncation."""\n'
        "    n = len(buf)\n"
        "    while off < n:\n"
        "        if off + REC_HDR.size > n:\n            raise ValueError(\"truncated record header\")\n"
        "        ch, enc, rf, length, seq, dt = REC_HDR.unpack_from(buf, off)\n"
        "        p = off + REC_HDR.size\n"
        "        if p + length > n:\n            raise ValueError(\"truncated record payload\")\n"
        "        yield Record(ch, enc, rf, length, seq, dt, p)\n"
        "        off = p + pad8(length)\n\n\n"
        "def encode_record(channel_id: int, encoding: int, rflags: int, seq: int, dt_us: int, payload: bytes) -> bytes:\n"
        "    n = len(payload)\n"
        "    return REC_HDR.pack(channel_id, encoding, rflags, n, seq & 0xFFFFFFFF, dt_us) + payload + b\"\\0\" * (pad8(n) - n)\n\n\n"
        "def encode_batch(flags: int, epoch: int, frame_seq: int, t_sim_ns: int, records: list[bytes]) -> bytes:\n"
        "    return FRAME_HDR.pack(OP_BATCH, flags, epoch & 0xFFFF, frame_seq & 0xFFFFFFFF, t_sim_ns) + b\"\".join(records)\n"
    )
    awrt = S["awr.fixture.AwrtHeader.v1"]["fields"]
    out.append(
        "\n\n# ---------------------------------------------------------------- .awrrt protocol fixtures (AWR-16 §13.9)\n"
        f"AWRT_MAGIC = {const_of(awrt, 'magic')}\nAWRT_VERSION = {const_of(awrt, 'version')}\nAWRT_TIMED = 0x01\n"
        "AWRT_S2C, AWRT_C2S = 0, 1\nAWRT_TEXT, AWRT_BINARY = 0, 1\n\n\n"
        "class AwrtRecord(NamedTuple):\n"
        "    dir: int\n    kind: int\n    t_rel_ns: int\n    payload: bytes\n\n\n"
        "class Awrrt(NamedTuple):\n"
        "    flags: int\n    t0_wall_ns: int\n    header: dict\n    records: list[AwrtRecord]\n\n\n"
        "def write_awrrt(header: dict, records: list[AwrtRecord], flags: int = AWRT_TIMED, t0_wall_ns: int = 0) -> bytes:\n"
        '    """Header JSON is written with sorted keys and no whitespace so fixtures are byte-reproducible."""\n'
        "    import json\n\n"
        "    hj = json.dumps(header, sort_keys=True, separators=(\",\", \":\"), ensure_ascii=False).encode()\n"
        "    parts = [AWRT_HDR.pack(AWRT_MAGIC, AWRT_VERSION, flags, len(hj), 0, t0_wall_ns), hj, b\"\\0\" * (pad8(len(hj)) - len(hj))]\n"
        "    last = -1\n"
        "    for r in records:\n"
        "        if r.t_rel_ns < last:\n            raise ValueError(\"t_rel_ns must be monotonic\")\n"
        "        last = r.t_rel_ns\n"
        "        n = len(r.payload)\n"
        "        parts += [AWRT_REC.pack(r.dir, r.kind, 0, n, r.t_rel_ns), bytes(r.payload), b\"\\0\" * (pad8(n) - n)]\n"
        "    return b\"\".join(parts)\n\n\n"
        "def read_awrrt(buf: bytes | memoryview) -> Awrrt:\n"
        "    import json\n\n"
        "    magic, version, flags, hlen, _res, t0 = AWRT_HDR.unpack_from(buf, 0)\n"
        "    if magic != AWRT_MAGIC or version != AWRT_VERSION:\n"
        "        raise ValueError(f\"not an .awrrt v1 file: magic=0x{magic:08x} version={version}\")\n"
        "    off = AWRT_HDR.size\n"
        "    header = json.loads(bytes(buf[off:off + hlen]).decode(\"utf-8\"))\n"
        "    off += pad8(hlen)\n"
        "    recs: list[AwrtRecord] = []\n"
        "    n = len(buf)\n"
        "    while off < n:\n"
        "        if off + AWRT_REC.size > n:\n            raise ValueError(\"truncated .awrrt record header\")\n"
        "        d, k, _r, length, t_rel = AWRT_REC.unpack_from(buf, off)\n"
        "        p = off + AWRT_REC.size\n"
        "        if p + length > n:\n            raise ValueError(\"truncated .awrrt record payload\")\n"
        "        recs.append(AwrtRecord(d, k, t_rel, bytes(buf[p:p + length])))\n"
        "        off = p + pad8(length)\n"
        "    return Awrrt(flags, t0, header, recs)\n"
    )
    return "".join(out)


# ---------------------------------------------------------------- reasons
def gen_reasons(c: dict) -> str:
    R = c["reasons"]
    out = [HDR.format(doc="Reason codes from packages/contracts/rt/reasons.json (AWR-17 §8)."),
           "from __future__ import annotations\n\nfrom enum import IntEnum\nfrom typing import NamedTuple\n\n\n",
           "class Reason(IntEnum):\n"]
    out.extend(f"    {r['name']} = {r['code']}\n" for r in R["reasons"])
    out.append("\n\nclass ReasonInfo(NamedTuple):\n    code: int\n    name: str\n    http: int | None\n    category: str\n"
               "    step: str | None\n    message_zh: str\n    remedy_zh: str\n    d1: str\n\n\n")
    out.append("REASONS: dict[int, ReasonInfo] = {\n")
    out.extend(f"    {r['code']}: ReasonInfo({r['code']}, {pylit(r['name'])}, {pylit(r['http'])}, {pylit(r['category'])}, "
                   f"{pylit(r['step'])}, {pylit(r['message_zh'])}, {pylit(r['remedy_zh'])}, {pylit(r['d1'])}),\n" for r in R["reasons"])
    out.append("}\n\n")
    out.append("DETAIL_ONLY: frozenset[str] = frozenset(" + pylit(R["detail_only"]) + ")\n")
    out.append("WARNINGS: frozenset[str] = frozenset(" + pylit(R["warnings"]) + ")\n")
    out.append("WS_CLOSE: dict[str, int] = {" + ", ".join(f"{json.dumps(w['name'])}: {w['code']}" for w in R["ws_close_codes"]) + "}\n\n\n")
    out.append("def info(code: int) -> ReasonInfo:\n    return REASONS[int(code)]\n\n\n"
               "def http_status(code: int) -> int:\n"
               '    """HTTP status for a REST problem+json response; codes without a mapping use 409."""\n'
               "    h = REASONS[int(code)].http\n    return 409 if h is None else h\n")
    return "".join(out)


