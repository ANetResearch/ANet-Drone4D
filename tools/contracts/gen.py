def gen_bus_keys(c: dict) -> str:
    K = c["keys"]
    out = [HDR.format(doc="Zenoh key space from packages/contracts/bus/keys.json (AWR-17 §9.3). Key literals are allowed only in this module."),
           "from __future__ import annotations\n\nimport re\n\n",
           f"NAMESPACE_FMT = {pylit(K['namespace'])}\nCHUNK_RE = re.compile({pylit(K['chunk_pattern'])})\n",
           f"EVENT_CATEGORIES: tuple[str, ...] = {pylit(K['event_categories'])}\n",
           f"PRODUCERS: tuple[str, ...] = {pylit(K['producers'])}\n\n\n",
           "def _chunk(x: str) -> str:\n"
           "    if not CHUNK_RE.match(x):\n        raise ValueError(f\"invalid key chunk: {x!r}\")\n"
           "    return x\n\n\n",
           "def namespace(world: str, run: str) -> str:\n"
           '    return NAMESPACE_FMT.format(world=_chunk(world), run=_chunk(run))\n\n\n']
    for k in K["keys"]:
        params = re.findall(r"\{(\w+)\}", k["key"])
        fn = k["name"].lower()
        if params:
            sig = ", ".join(f"{p}: str" for p in params)
            body = "f" + json.dumps(re.sub(r"\{(\w+)\}", lambda m: "{_chunk(" + m.group(1) + ")}", k["key"]))
            out.append(f"def {fn}({sig}) -> str:\n    return {body}\n\n\n")
        else:
            out.append(f"{k['name']} = {json.dumps(k['key'])}\n\n\n")
    return "".join(out).rstrip() + "\n"


