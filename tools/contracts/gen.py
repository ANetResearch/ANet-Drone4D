def pylit(v) -> str:
    """Deterministic Python literal for JSON-like values."""
    if v is None:
        return "None"
    if v is True:
        return "True"
    if v is False:
        return "False"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        return "(" + ", ".join(pylit(x) for x in v) + ("," if len(v) == 1 else "") + ")"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{json.dumps(k, ensure_ascii=False)}: {pylit(x)}" for k, x in v.items()) + "}"
    raise TypeError(type(v))


def jsonlit(v) -> str:
    """Python literal that keeps JSON lists as lists (for JSON Schema payloads)."""
    if isinstance(v, list):
        return "[" + ", ".join(jsonlit(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{json.dumps(k, ensure_ascii=False)}: {jsonlit(x)}" for k, x in v.items()) + "}"
    return pylit(v)


