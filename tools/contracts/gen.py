    out.append("ADMISSION_COLUMNS: tuple[str, ...] = " + pylit([x["id"] for x in cols]) + "\n")
    out.append("ADMISSION_SYMBOL_CODE: dict[str, int] = " + pylit({k: v["code"] for k, v in C["admission_symbols"].items()}) + "\n")
    out.append("ADMISSION_CONDITION_ELSE: dict[str, str] = " + pylit({k: v["else"] for k, v in C["admission_conditions"].items()}) + "\n\n")
    out.append("\nclass Service(NamedTuple):\n    name: str\n    op: str\n    pattern: re.Pattern[str]\n    category: str\n    lease: bool | str | None\n"
               "    agent: str\n    d1: str\n    batchable: bool\n    aliases: tuple[str, ...]\n    args_schema: dict[str, Any]\n"
               "    admission: tuple[str, ...] | None\n    admission_cond: dict[str, str]\n\n\n")
    out.append("def _pattern(name: str) -> re.Pattern[str]:\n"
               '    return re.compile("^" + re.sub(r"\\\\\\{(\\w+)\\\\\\}", lambda m: f"(?P<{m.group(1)}>[a-z0-9][a-z0-9_-]*)", re.escape(name)) + "$")\n\n\n')
    out.append("SERVICES: tuple[Service, ...] = (\n")
    for s in C["services"]:
        adm = pylit([s["admission"][cid["id"]] for cid in cols]) if "admission" in s else "None"
        out.append(f"    Service({pylit(s['name'])}, {pylit(s['op'])}, _pattern({pylit(s['name'])}), {pylit(s['category'])}, {pylit(s['lease'])}, "
                   f"{pylit(s['agent'])}, {pylit(s['d1'])}, {pylit(s.get('batchable', False))}, {pylit(s.get('aliases', []))},\n"
                   f"            {jsonlit(s['args_schema'])},\n            {adm}, {pylit(s.get('admission_cond', {}))}),\n")
    out.append(")\n\nSERVICE_BY_OP: dict[str, Service] = {s.op: s for s in SERVICES}\n")
    out.append("_ALIAS: list[tuple[re.Pattern[str], Service]] = [(_pattern(a), s) for s in SERVICES for a in s.aliases]\n\n\n")
    out.append("def match_service(name: str) -> tuple[Service, dict[str, str]] | None:\n"
               '    """Resolve a WS service name (uav/{id}/cmd/goto, fleet/cmd/rtl, sim/play ...) to its Service and path parameters."""\n'
               "    for s in SERVICES:\n"
               "        m = s.pattern.match(name)\n"
               "        if m:\n            return s, m.groupdict()\n"
               "    for p, s in _ALIAS:\n"
               "        m = p.match(name)\n"
               "        if m:\n            return s, m.groupdict()\n"
               "    return None\n\n\n")
    out.append("def admission_column(fs: int, flags: int) -> int:\n"
               '    """Column index of the admission matrix: RTL and LANDING split by flags.FAILSAFE (operator vs automatic)."""\n'
               "    auto = bool(flags & FlightFlags.FAILSAFE)\n"
               "    order = [FlightState.UNKNOWN, FlightState.DISARMED, FlightState.PREFLIGHT, FlightState.READY, FlightState.TAKING_OFF,\n"
               "             FlightState.FLYING, FlightState.CORRECTING, FlightState.HOLD]\n"
               "    if fs in order:\n        return order.index(fs)\n"
               "    if fs == FlightState.RTL:\n        return 9 if auto else 8\n"
               "    if fs == FlightState.LANDING:\n        return 11 if auto else 10\n"
               "    return {FlightState.ELAND: 12, FlightState.FAILSAFE: 13, FlightState.LANDED: 14, FlightState.CRASHED: 15}[FlightState(fs)]\n\n\n"
               "def admit_symbol(op: str, fs: int, flags: int) -> tuple[str, str | None]:\n"
               '    """(symbol, condition id) for a vehicle command; symbol Y, =, S, - (AWR-12 §5.2). Conditions are applied by the caller."""\n'
               "    s = SERVICE_BY_OP[op]\n"
               "    if s.admission is None:\n        raise KeyError(f\"{op} has no admission row\")\n"
               "    col = admission_column(fs, flags)\n"
               "    return s.admission[col], s.admission_cond.get(ADMISSION_COLUMNS[col])\n")
    return "".join(out)


