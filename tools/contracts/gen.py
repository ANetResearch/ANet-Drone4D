# ---------------------------------------------------------------- schema TypedDicts
def _union(parts: list[str]) -> str:
    flat: list[str] = []
    for p in parts:
        for q in p.split(" | "):
            if q not in flat:
                flat.append(q)
    flat.sort(key=lambda q: q == "None")
    return " | ".join(flat) if flat else "Any"


class TypeGen:
    """JSON Schema (all files under packages/contracts) -> TypedDict definitions and type aliases."""

    def __init__(self):
        self.docs: dict[str, tuple[Path, dict]] = {}
        for p in L.schema_files():
            d = json.loads(p.read_text(encoding="utf-8"))
            self.docs[d["$id"]] = (p, d)
        self.names: dict[tuple[str, str], str] = {}
        used: set[str] = set()
        for sid, (p, _d) in sorted(self.docs.items()):
            dom = sid.split("/")[3]
            stem = p.name[: -len(".schema.json")]
            base = self._pascal(stem)
            if base in used or base in {"Command", "Event", "Detail", "Common"}:
                base = self._pascal(dom) + base
            used.add(base)
            self.names[(sid, "")] = base
        self.blocks: dict[str, str] = {}
        self.kinds: dict[str, str] = {}
        self.deps: dict[str, set[str]] = {}

    @staticmethod
    def _pascal(s: str) -> str:
        return "".join(w[:1].upper() + w[1:] for w in re.split(r"[-_./@ $]+", s) if w)

    def ref_target(self, sid: str, ref: str) -> tuple[str, str]:
        if ref.startswith("#"):
            return sid, ref[1:]
        base, _, frag = ref.partition("#")
        parts = sid.rsplit("/", 1)[0].split("/")
        for seg in base.split("/"):
            if seg == "..":
                parts.pop()
            elif seg and seg != ".":
                parts.append(seg)
        return "/".join(parts), frag

    def node(self, sid: str, ptr: str):
        d = self.docs[sid][1]
        for seg in [s for s in ptr.split("/") if s]:
            d = d[int(seg)] if isinstance(d, list) else d[seg.replace("~1", "/").replace("~0", "~")]
        return d

    def name_for(self, sid: str, ptr: str) -> str:
        key = (sid, ptr)
        if key not in self.names:
            base = self.names[(sid, "")]
            tail = [s for s in ptr.split("/") if s and s not in ("$defs", "properties", "items", "definitions", "additionalProperties")]
            name = base + "".join(self._pascal(t) for t in tail if not t.isdigit()) + "".join(t for t in tail if t.isdigit())
            while name in self.names.values():
                name += "_"
            self.names[key] = name
        return self.names[key]

    def annot(self, sid: str, ptr: str, s) -> str:
        if s is True or s == {} or not isinstance(s, dict):
            return "Any"
        if "$ref" in s:
            tsid, tptr = self.ref_target(sid, s["$ref"])
            return self.named(tsid, tptr)
        if "const" in s:
            return f"Literal[{pylit(s['const'])}]" if not isinstance(s["const"], (list, dict)) else "Any"
        if "enum" in s:
            vals = [v for v in s["enum"] if not isinstance(v, (list, dict))]
            lits = [pylit(v) for v in vals if v is not None]
            a = f"Literal[{', '.join(lits)}]" if lits else "None"
            return a + (" | None" if None in s["enum"] and lits else "")
        for comb in ("oneOf", "anyOf"):
            if comb in s and not s.get("properties"):
                parts: list[str] = []
                for i, sub in enumerate(s[comb]):
                    a = self.annot(sid, f"{ptr}/{comb}/{i}", sub)
                    if a not in parts:
                        parts.append(a)
                return _union(parts)
        t = s.get("type")
        if isinstance(t, list):
            parts = []
            for tt in t:
                a = self.annot(sid, ptr, {**s, "type": tt})
                if a not in parts:
                    parts.append(a)
            return _union(parts)
        if t == "string":
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "float"
        if t == "boolean":
            return "bool"
        if t == "null":
            return "None"
        if t == "array":
            it = s.get("items")
            return f"list[{self.annot(sid, ptr + '/items', it)}]" if isinstance(it, dict) else "list[Any]"
        if t == "object" or "properties" in s:
            if s.get("properties"):
                return self.named(sid, ptr)
            ap = s.get("additionalProperties")
            if isinstance(ap, dict):
                return f"dict[str, {self.annot(sid, ptr + '/additionalProperties', ap)}]"
            return "dict[str, Any]"
        return "Any"

    def named(self, sid: str, ptr: str) -> str:
        """Emit (once) a TypedDict for object schemas or a type alias for other named definitions; return its name."""
        name = self.name_for(sid, ptr)
        if name in self.kinds:
            return name
        s = self.node(sid, ptr)
        self.kinds[name] = "pending"  # recursion guard
        src = f"# {self.docs[sid][0].relative_to(L.CONTRACTS)}#{ptr}"
        doc = (s.get("title") or "").replace("\n", " ") if isinstance(s, dict) else ""
        head = f"{src}{(' ' + doc[:100]) if doc else ''}\n"
        if isinstance(s, dict) and s.get("properties"):
            req = set(s.get("required", []))
            items = [(k, self.annot(sid, f"{ptr}/properties/{k}", sub), k in req) for k, sub in s["properties"].items()]
            if all(k.isidentifier() and not keyword.iskeyword(k) for k, _, _ in items):
                body = "".join(f"    {k}: {a if r else f'NotRequired[{a}]'}\n" for k, a, r in items)
                self.kinds[name] = "class"
                self.blocks[name] = f"{head}class {name}(TypedDict):\n{body}"
            else:
                body = "".join(f"    {json.dumps(k)}: {a if r else f'NotRequired[{a}]'},\n" for k, a, r in items)
                self.kinds[name] = "functional"
                self.deps[name] = set(re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", "".join(a for _, a, _ in items)))
                self.blocks[name] = f"{head}{name} = TypedDict(\"{name}\", {{\n{body}}})\n"
        else:
            self.kinds[name] = "alias"
            self.blocks[name] = f"{head}type {name} = {self.annot(sid, ptr, s) if isinstance(s, dict) else 'Any'}\n"
        return name

    def run(self) -> str:
        for sid in sorted(self.docs):
            d = self.docs[sid][1]
            self.named(sid, "")
            for k in d.get("$defs", {}):
                self.named(sid, f"/$defs/{k}")
        aliases = sorted(n for n, k in self.kinds.items() if k == "alias")
        classes = sorted(n for n, k in self.kinds.items() if k == "class")
        funcs = sorted(n for n, k in self.kinds.items() if k == "functional")
        ordered: list[str] = []
        seen: set[str] = set()

        def visit(n: str, stack: tuple[str, ...] = ()) -> None:
            if n in seen or n in stack:
                return
            for d in sorted(self.deps.get(n, ())):
                if self.kinds.get(d) == "functional":
                    visit(d, (*stack, n))
            seen.add(n)
            ordered.append(n)

        for n in funcs:
            visit(n)
        body = "\n\n".join(self.blocks[n] for n in [*aliases, *classes, *ordered])
        imports = ["Any", "Literal", "NotRequired", "TypedDict"]
        imports = [i for i in imports if re.search(rf"\b{i}\b", body)]
        allnames = sorted(self.blocks)
        head = (HDR.format(doc="TypedDict definitions and type aliases for every JSON Schema under packages/contracts (keys as on the wire).")
                + "from __future__ import annotations\n\n"
                + f"from typing import {', '.join(imports)}\n\n"
                + "__all__ = [\n" + "".join(f"    \"{n}\",\n" for n in allnames) + "]\n\n")
        return head + body


def build(c: dict) -> dict[Path, str]:
    P = L.PY_OUT
    files = {
        P / "__init__.py": gen_init(c),
        P / "_paths.py": gen_paths(),
        P / "enums.py": gen_enums(c),
        P / "layouts.py": gen_layouts(c),
        P / "frame.py": gen_frame(c),
        P / "reasons.py": gen_reasons(c),
        P / "commands.py": gen_commands(c),
        P / "topics.py": gen_topics(c),
        P / "units.py": gen_units(c),
        P / "bus_keys.py": gen_bus_keys(c),
        P / "rng_streams.py": gen_rng(c),
        P / "safety_codes.py": gen_safety(c),
        P / "presets.py": gen_presets(c),
        P / "schema_types.py": TypeGen().run(),
    }
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with committed output, do not write")
    args = ap.parse_args(argv)
    try:
        c = L.load_all()
        files = build(c)
    except L.ContractError as e:
        print(f"contract error: {e}", file=sys.stderr)
        return 2
    diffs = L.write_or_check(files, args.check, L.PY_OUT)
    if args.check and diffs:
        print(f"gen.py --check: {diffs} file(s) differ; run python tools/contracts/gen.py", file=sys.stderr)
        return 1
    print(f"gen.py: {'up to date' if not diffs else f'{diffs} file(s) updated'} (layout_id 0x{c['layout_id']:08X}, contracts {c['version']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())

