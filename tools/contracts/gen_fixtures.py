# ---------------------------------------------------------------- helpers
def jtext(obj) -> bytes:
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False).encode()


def rec(dir_: int, kind: int, t_ms: float, payload: bytes) -> F.AwrtRecord:
    return F.AwrtRecord(dir_, kind, round(t_ms * MS), payload)


