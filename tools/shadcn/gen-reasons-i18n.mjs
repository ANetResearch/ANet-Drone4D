#!/usr/bin/env node
// Reason code texts (M15-FR-104; AWR-14 §13.6; AWR-17 §8): packages/contracts/rt/reasons.json (message_zh, remedy_zh)
// -> apps/web/src/app/i18n/reasons.zh-CN.gen.json with keys reason.<code>.short and reason.<code>.remedy, and
// apps/web/src/app/i18n/reasons.gen.ts with the list of known codes. The texts stay in JSON so that no TS file under
// app/** holds CJK literals (lint I18N-01); unknown codes use the key reason.unknown ("未知原因（码 {code}）").
// Usage: node tools/shadcn/gen-reasons-i18n.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SRC = join(ROOT, 'packages', 'contracts', 'rt', 'reasons.json')
const OUT_JSON = join(ROOT, 'apps', 'web', 'src', 'app', 'i18n', 'reasons.zh-CN.gen.json')
const OUT_TS = join(ROOT, 'apps', 'web', 'src', 'app', 'i18n', 'reasons.gen.ts')

const doc = JSON.parse(readFileSync(SRC, 'utf8'))
const dict = {}
const codes = []
for (const r of doc.reasons) {
  codes.push(r.code)
  dict[`reason.${r.code}.short`] = r.message_zh
  dict[`reason.${r.code}.remedy`] = r.remedy_zh
}
const json = JSON.stringify(dict, null, 1) + '\n'
const ts = [
  '// GENERATED by tools/shadcn/gen-reasons-i18n.mjs from packages/contracts/rt/reasons.json. DO NOT EDIT.',
  '// Reason code texts live in reasons.zh-CN.gen.json (keys reason.<code>.short / reason.<code>.remedy).',
  `export const REASON_CODES: readonly number[] = [${codes.join(', ')}]`,
  `export const REASON_NAMES: Readonly<Record<number, string>> = ${JSON.stringify(Object.fromEntries(doc.reasons.map((r) => [r.code, r.name])))}`,
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const stale = [[OUT_JSON, json], [OUT_TS, ts]].filter(([p, t]) => !existsSync(p) || readFileSync(p, 'utf8') !== t)
  if (stale.length) {
    for (const [p] of stale) console.error(`gen-reasons-i18n: ${p} is out of date; run node tools/shadcn/gen-reasons-i18n.mjs`)
    process.exit(1)
  }
  console.log(`gen-reasons-i18n: up to date (${codes.length} codes)`)
} else {
  writeFileSync(OUT_JSON, json)
  writeFileSync(OUT_TS, ts)
  console.log(`gen-reasons-i18n: ${codes.length} codes`)
}
