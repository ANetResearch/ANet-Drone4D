    panelOpenMs: d('--panel-open-dur'), panelCloseMs: d('--panel-close-dur'), dropdownOpenMs: d('--dropdown-open-dur'),
    dropdownCloseMs: d('--dropdown-close-dur'), modalOpenMs: d('--modal-open-dur'), modalCloseMs: d('--modal-close-dur'),
    iconSwapMs: d('--icon-swap-dur'), textSwapMs: d('--text-swap-dur'), toastOpenMs: d('--toast-open'), toastCloseMs: d('--toast-close'),
    digitMs: d('--digit-dur'), digitStaggerMs: d('--digit-stagger'), shakeSegmentAMs: d('--shake-dur-a'), shakeSegmentBMs: d('--shake-dur-b'),
