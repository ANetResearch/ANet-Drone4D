#!/usr/bin/env node
// Token generator (M15-FR-045, FR-050; AWR-15 §13.6; ADR-029): the CSS token files are the single source; this script
// exports them as TypeScript constants for engine/** (TSL uniforms, camera flight, LOD fade), canvas charts and JS recipes,
// so no duration, easing or colour literal appears in TS/TSL code (MOT-01, VIS-L-01).
//   styles/motion/tokens.css + styles/motion/ext-tokens.css + tools/shadcn/tokens/motion.json -> lib/tokens/motion.gen.ts
//   styles/theme.css (primitive layer)                                                         -> lib/tokens/palette.gen.ts
//   styles/theme.css (scene layer)                                                             -> lib/tokens/scene.gen.ts
//   tools/shadcn/tokens/input.json                                                             -> lib/tokens/input.gen.ts
// Colours are emitted as floats (sRGB 0-1 in palette, linear sRGB in scene); no hex is written.
// Usage: node tools/shadcn/gen-theme-tokens.mjs [--check]   (--check: exit 1 when a generated file is out of date)
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const WEB = join(ROOT, 'apps', 'web', 'src')
const read = (p) => readFileSync(p, 'utf8')
const HEADER = (src) => `// GENERATED by tools/shadcn/gen-theme-tokens.mjs from ${src}. DO NOT EDIT.\n`

// ------------------------------------------------------------------ CSS parsing
const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '')
function decls(css) {
  const out = new Map()
  for (const m of stripComments(css).matchAll(/(--[a-z0-9-]+)\s*:\s*([^;{}]+);/g)) if (!out.has(m[1])) out.set(m[1], m[2].trim())
  return out
}
/** Declarations inside the first block whose selector matches `selector` (exact text before `{`). */
function blockDecls(css, selector) {
  const src = stripComments(css)
  const i = src.indexOf(selector + ' {')
  if (i < 0) return new Map()
  let depth = 0
  let j = src.indexOf('{', i)
  const start = j
  for (; j < src.length; j++) {
    if (src[j] === '{') depth++
    else if (src[j] === '}' && --depth === 0) break
  }
  return decls(src.slice(start + 1, j))
}
const ms = (v) => {
  const m = /^(-?\d*\.?\d+)(ms|s)$/.exec(String(v).trim())
  if (!m) throw new Error(`not a duration: ${v}`)
  return m[2] === 's' ? Number(m[1]) * 1000 : Number(m[1])
}
const px = (v) => {
  const m = /^(-?\d*\.?\d+)px$/.exec(String(v).trim())
  if (!m) throw new Error(`not a length in px: ${v}`)
  return Number(m[1])
}
const KEYWORD_EASE = { 'ease-in-out': [0.42, 0, 0.58, 1], 'ease-out': [0, 0, 0.58, 1], 'ease-in': [0.42, 0, 1, 1], ease: [0.25, 0.1, 0.25, 1], linear: [0, 0, 1, 1] }
function bezier(v) {
  const s = String(v).trim()
  if (KEYWORD_EASE[s]) return KEYWORD_EASE[s]
  const m = /^cubic-bezier\(([^)]+)\)$/.exec(s)
  if (!m) throw new Error(`not an easing: ${v}`)
  return m[1].split(',').map((x) => Number(x.trim()))
}
const camel = (k) => k.replace(/^--/, '').replace(/-([a-z0-9])/g, (_m, c) => c.toUpperCase())
const round = (x, n = 6) => Number(x.toFixed(n))

// ------------------------------------------------------------------ motion
