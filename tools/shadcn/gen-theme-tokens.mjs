    cameraMinMs: d('--duration-camera-min', eroot), cameraMaxMs: d('--duration-camera-max', eroot), lodFadeMs: d('--duration-lod-fade', eroot),
    chartEnterMs: d('--duration-chart-enter', eroot), chartSlowMs: d('--duration-chart-slow', eroot),
    telemetryAnimIntervalMs: d('--telemetry-anim-interval', eroot),
    telemetryTextIntervalMs: { S: d('--telemetry-text-interval', tierS), B: d('--telemetry-text-interval', eroot), A: d('--telemetry-text-interval', eroot) },
    staggerCapMs: { full: d('--stagger-cap', eroot), lite: Math.round(d('--stagger-cap', eroot) / 2) },
    springSettleMs: json.springSettleMs,
