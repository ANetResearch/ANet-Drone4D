// ------------------------------------------------------------------ colours
const hexRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
const toLin = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)
const lum = (rgb) => {
  const [r, g, b] = rgb.map(toLin)
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a, b) => {
  const la = lum(a)
  const lb = lum(b)
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05)
}
function primitives(themeCss) {
  const out = {}
  for (const m of stripComments(themeCss).matchAll(/--(g\d+|white|r\d+)\s*:\s*(#[0-9A-Fa-f]{6})\s*;/g)) out[m[1]] = hexRgb(m[2])
  if (Object.keys(out).length !== 18) throw new Error(`theme.css: expected 18 primitive colours, found ${Object.keys(out).length}`)
  return out
}

function genPalette() {
  const P = primitives(read(join(WEB, 'styles/theme.css')))
  const srgb = Object.fromEntries(Object.entries(P).map(([k, v]) => [k, v.map((x) => round(x))]))
  const lin = Object.fromEntries(Object.entries(P).map(([k, v]) => [k, v.map((x) => round(toLin(x)))]))
  const pairs = [['g50', 'g950'], ['g50', 'g900'], ['g50', 'g850'], ['g300', 'g900'], ['g200', 'g900'], ['white', 'r600'], ['r400', 'g900'],
    ['r500', 'g900'], ['g900', 'g50'], ['g500', 'g50'], ['r700', 'g50'], ['g400', 'g900'], ['g500', 'g900']]
  const table = Object.fromEntries(pairs.map(([f, b]) => [`${f}/${b}`, round(contrast(P[f], P[b]), 2)]))
  return [HEADER('styles/theme.css (primitive layer, AWR-15 §3.1-§3.2)'),
    'export type Rgb = readonly [number, number, number]',
    'export type PrimitiveName = ' + Object.keys(P).map((k) => `'${k}'`).join(' | '), '',
    '/** gamma-encoded sRGB, components 0-1 */',
    `export const PALETTE: Readonly<Record<PrimitiveName, Rgb>> = ${JSON.stringify(srgb)}`, '',
    '/** linear sRGB, components 0-1 (TSL uniforms, canvas maths) */',
    `export const PALETTE_LINEAR: Readonly<Record<PrimitiveName, Rgb>> = ${JSON.stringify(lin)}`, '',
    '/** WCAG 2.x contrast ratios of the documented text and mark roles (AWR-15 §3.1-§3.3), foreground/background */',
    `export const CONTRAST: Readonly<Record<string, number>> = ${JSON.stringify(table, null, 2)}`, ''].join('\n')
}

function genScene() {
  const css = read(join(WEB, 'styles/theme.css'))
  const P = primitives(css)
  const root = blockDecls(css, ':root')
  const linOf = (name) => P[name].map((x) => round(toLin(x)))
  const color = (k) => {
    const v = root.get(k)
    if (!v) throw new Error(`scene token ${k} missing in theme.css`)
    let m = /^var\(--(g\d+|white|r\d+)\)$/.exec(v)
    if (m) return linOf(m[1])
    m = /^oklch\(from var\(--(g\d+|white|r\d+)\) l c h \/ ([\d.]+)\)$/.exec(v)
    if (m) return { rgb: linOf(m[1]), a: Number(m[2]) }
    throw new Error(`scene token ${k}: unsupported value ${v}`)
  }
  const num = (k) => Number(root.get(k))
  const presets = [...root.keys()].filter((k) => k.startsWith('--scene-horizon-')).map((k) => k.slice('--scene-horizon-'.length))
  const pid = (kebab) => kebab.replace(/-([a-z])/g, (_m, c) => c.toUpperCase())
  const S = {
    clear: color('--scene-clear'), skyZenith: color('--scene-sky-zenith'), skyHorizon: color('--scene-sky-horizon'),
    skyHorizonByPreset: Object.fromEntries(presets.map((p) => [pid(p), color(`--scene-horizon-${p}`)])),
    cloudMaxByPreset: Object.fromEntries(presets.map((p) => [pid(p), num(`--scene-cloud-max-${p}`)])),
    gridMinor: color('--scene-grid-minor'), gridMajor: color('--scene-grid-major'),
    pcRamp: [0, 1, 2, 3, 4].map((i) => color(`--pc-ramp-${i}`)), pcHero: color('--pc-hero'),
    pcGamma: num('--pc-gamma'), pcHeroMix: num('--pc-hero-mix'), edlStrength: num('--pc-edl-strength'), edlRadiusPx: num('--pc-edl-radius'),
    droneMarker: color('--drone-marker'), droneHalo: color('--drone-halo'), droneStale: color('--drone-stale'), droneBody: color('--drone-body'),
    droneArm: color('--drone-arm'), droneArmFront: color('--drone-arm-front'), droneRotor: color('--drone-rotor'),
    glyphPalette: [color('--glyph-select'), color('--glyph-alert'), color('--drone-stale'), linOf('g400'), linOf('g300'), linOf('g200')],
    trailDefault: color('--trail-default'), trailSelected: color('--trail-selected'), pathPlanned: color('--path-planned'), pathDone: color('--path-done'),
    fovEdge: color('--fov-edge'), fovFill: color('--fov-fill'),
    windRamp: [1, 2, 3, 4, 5].map((i) => color(`--wind-ramp-${i}`)),
    precipRain: color('--precip-rain'), precipSnow: color('--precip-snow'), precipDust: color('--precip-dust'), cloud2d: color('--cloud-2d'),
    classColors: Array.from({ length: 16 }, (_x, i) => color(`--pc-class-${i}`)),
  }
  return [HEADER('styles/theme.css (scene layer, AWR-15 §10.2-§10.3, §13.6)'),
    '/** linear sRGB, components 0-1 */',
    'export type Lin3 = readonly [number, number, number]',
    'export interface LinA { readonly rgb: Lin3; readonly a: number }',
    `export type ScenePresetId = ${presets.map((p) => `'${pid(p)}'`).join(' | ')}`,
    'export interface SceneTokens {',
    '  clear: Lin3; skyZenith: Lin3; skyHorizon: Lin3',
    '  skyHorizonByPreset: Readonly<Record<ScenePresetId, Lin3>>; cloudMaxByPreset: Readonly<Record<ScenePresetId, number>>',
    '  gridMinor: LinA; gridMajor: LinA; pcRamp: readonly Lin3[]; pcHero: Lin3',
    '  pcGamma: number; pcHeroMix: number; edlStrength: number; edlRadiusPx: number',
    '  droneMarker: Lin3; droneHalo: Lin3; droneStale: Lin3; droneBody: Lin3; droneArm: Lin3; droneArmFront: Lin3; droneRotor: Lin3',
    '  /** index: 0 g50 selected, 1 r500 red entity and alerts, 2 g500 stale, 3 g400, 4 g300, 5 g200 */',
    '  glyphPalette: readonly Lin3[]',
    '  trailDefault: Lin3; trailSelected: Lin3; pathPlanned: Lin3; pathDone: Lin3; fovEdge: LinA; fovFill: LinA',
    '  windRamp: readonly Lin3[]; precipRain: LinA; precipSnow: LinA; precipDust: LinA; cloud2d: Lin3',
    '  /** anet-classes@1 index 0-15 (15 is reserved, g600 placeholder) */',
    '  classColors: readonly Lin3[]',
    '}',
    `export const SCENE: SceneTokens = ${JSON.stringify(S)}`, ''].join('\n')
}

function genInput() {
  const j = JSON.parse(read(join(ROOT, 'tools/shadcn/tokens/input.json')))
  const INPUT = { ...j.input, ...j.red, ...j.timers }
  return [HEADER('tools/shadcn/tokens/input.json'),
    '/** input thresholds (AWR-14 §6.1), one-red arbitration (AWR-15 §3.7.2) and M15 presentation timers (M15 §6.14); ms, px, Hz */',
    `export const INPUT = ${JSON.stringify(INPUT, null, 2)} as const`, '',
    '/** capacities and caps (M15 §6.14) */', `export const LIMITS = ${JSON.stringify(j.limits, null, 2)} as const`, '',
    '/** shell geometry in CSS px (AWR-14 §3.3, §14.1) */', `export const LAYOUT = ${JSON.stringify(j.layout, null, 2)} as const`, '',
    '/** lieflat scheduler and canvas limits (ADR-031; d01 §3.6) */', `export const LF = ${JSON.stringify(j.lf, null, 2)} as const`, '',
    '/** DOM motion budget (ADR-029; d02 §4.7) and morph concurrency K (ADR-030) */', `export const MOTION_BUDGET = ${JSON.stringify(j.motionBudget, null, 2)} as const`, '',
    '/** telemetry icon buckets (d03 §3.6) */', `export const ICON_BUCKETS = ${JSON.stringify(j.icons)} as const`, ''].join('\n')
}

const INDEX = [HEADER('the list of token modules'),
  "export * from './motion.gen'", "export * from './palette.gen'", "export * from './scene.gen'", "export * from './input.gen'", ''].join('\n')

const OUTPUTS = [['motion.gen.ts', genMotion], ['palette.gen.ts', genPalette], ['scene.gen.ts', genScene], ['input.gen.ts', genInput], ['index.ts', () => INDEX]]
const dir = join(WEB, 'lib', 'tokens')
const check = process.argv.includes('--check')
let stale = 0
mkdirSync(dir, { recursive: true })
for (const [name, gen] of OUTPUTS) {
  const text = gen()
  const p = join(dir, name)
  if (check) {
    if (!existsSync(p) || read(p) !== text) {
      console.error(`gen-theme-tokens: lib/tokens/${name} is out of date; run node tools/shadcn/gen-theme-tokens.mjs`)
      stale++
    }
  } else writeFileSync(p, text)
}
if (check && stale) process.exit(1)
console.log(`gen-theme-tokens: ${check ? 'up to date' : `wrote ${OUTPUTS.length} files in apps/web/src/lib/tokens`}`)
