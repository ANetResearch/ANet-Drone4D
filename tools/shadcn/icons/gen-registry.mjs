#!/usr/bin/env node
// Generate apps/web/src/ui/icons/{registry,whitelist,custom}.ts from tools/shadcn/icons/inventory.mjs
// (M15-FR-059, FR-062; AWR-15 §7.6; ADR-030). The registry uses quoted semantic keys and named lucide imports with
// canonical names only (ICON-03), so check-icons can read the key set (ICON-04).
// Usage: node tools/shadcn/icons/gen-registry.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { INVENTORY, CUSTOM } from './inventory.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const OUT = join(ROOT, 'apps', 'web', 'src', 'ui', 'icons')
const HEAD = '// GENERATED by tools/shadcn/icons/gen-registry.mjs from tools/shadcn/icons/inventory.mjs. DO NOT EDIT.\n'

// lucide names that shadow JS globals are imported under an alias
const ALIAS = { Map: 'MapIcon' }
const ident = (name) => (name.startsWith('custom:') ? name.slice(7) : ALIAS[name] ?? name)
const spec = (name) => (ALIAS[name] ? `${name} as ${ALIAS[name]}` : name)
const isCustom = (name) => name.startsWith('custom:') || Object.hasOwn(CUSTOM, name)

function genCustom() {
  const lines = [HEAD, '// Custom stroke icons on the 24 grid (AWR-15 §7.8; d03 §4.1).', "import type { IconNode } from './types'", '']
  for (const [name, node] of Object.entries(CUSTOM)) {
    lines.push(`export const ${name}: IconNode = ${JSON.stringify(node).replace(/"/g, "'")}`)
  }
  return lines.join('\n') + '\n'
}

function genRegistry() {
  const lucide = new Set()
  const custom = new Set()
  for (const [, , name, partner] of INVENTORY) {
    for (const n of [name, partner]) {
      if (!n) continue
      if (isCustom(n)) custom.add(ident(n))
      else lucide.add(n)
    }
  }
  const lines = [HEAD,
    '// Semantic icon registry (M15-FR-059; AWR-15 §7.6; ADR-030). Business code writes semantic keys only; geometry is',
    '// lucide@1.48.0 canonical IconNode data or one of the custom icons. PARTNERS holds the alternate geometry of a key',
    '// (the other end of a whitelisted morph pair or an explicit swap partner) for <StateIcon icon={key} alt>.',
    `import { ${[...lucide].sort().map(spec).join(', ')} } from 'lucide'`,
    `import { ${[...custom].sort().join(', ')} } from './custom'`,
    "import type { IconNode } from './types'", '',
    'export const ICONS = {']
  for (const [group, key, name] of INVENTORY) lines.push(`  '${key}': ${ident(name)}, // ${group}`)
  lines.push('} as const satisfies Record<string, IconNode>', '',
    'export type IconKey = keyof typeof ICONS', '',
    'export const PARTNERS: Readonly<Partial<Record<IconKey, IconNode>>> = {')
  for (const [, key, , partner] of INVENTORY) if (partner) lines.push(`  '${key}': ${ident(partner)},`)
  lines.push('}', '',
    '/** keys whose angle is shown with the CSS rotate property, never a morph (d03 §3.6; AWR-15 §7.5) */',
    `export const ROTATE_KEYS: ReadonlySet<IconKey> = new Set<IconKey>([${INVENTORY.filter((r) => r[4] === 'rot').map((r) => `'${r[1]}'`).join(', ')}])`, '',
    `export const ICON_KEY_COUNT = ${INVENTORY.length}`,
    `export const ICON_GEOMETRY_COUNT = ${new Set(INVENTORY.map((r) => r[2])).size}`, '')
  return lines.join('\n')
}

function genWhitelist() {
  const seen = new Set()
  const pairs = []
  for (const [, key, name, partner, mode, spring] of INVENTORY) {
    if (mode !== 'morph') continue
    const id = [ident(name), ident(partner)].sort().join('|')
    if (seen.has(id)) continue
    seen.add(id)
    pairs.push([ident(name), ident(partner), spring ?? 'snappy', key])
  }
  const names = [...new Set(pairs.flatMap((p) => [p[0], p[1]]))].sort()
  return [HEAD,
    '// Morph whitelist (M15-FR-062; d03 §4.2): only pairs that pass the four admission rules (same object, <= 2 subpath',
    '// difference or same family, max residual <= 0.5 or pure rotation, contact sheet) are registered; every other change',
    '// is a swap (transitions.dev 09). Rerun tools/shadcn/icons/verify.mjs and the contact sheet after a lucide upgrade.',
    `import { ${names.filter((n) => !Object.hasOwn(CUSTOM, n)).map(spec).join(', ')} } from 'lucide'`,
    "import type { IconNode } from './types'", '',
    "export type SpringName = 'snappy' | 'smooth' | 'hud'", '',
    '/** [from, to, default spring, registering key]; morph is allowed in both directions */',
    'export const MORPH_PAIRS: readonly (readonly [IconNode, IconNode, SpringName, string])[] = [',
    ...pairs.map(([a, b, s, k]) => `  [${a}, ${b}, '${s}', '${k}'],`),
    ']', '',
    'const OK = new Map<IconNode, Map<IconNode, SpringName>>()',
    'for (const [a, b, s] of MORPH_PAIRS) {',
    '  if (!OK.has(a)) OK.set(a, new Map())',
    '  if (!OK.has(b)) OK.set(b, new Map())',
    '  OK.get(a)!.set(b, s)',
    '  OK.get(b)!.set(a, s)',
    '}', '',
    '/** default spring of a whitelisted pair, or null when the change must be a swap */',
    'export function morphSpring(from: IconNode, to: IconNode): SpringName | null {',
    '  return OK.get(from)?.get(to) ?? null',
    '}', ''].join('\n')
}

const outputs = [['custom.ts', genCustom], ['registry.ts', genRegistry], ['whitelist.ts', genWhitelist]]
const check = process.argv.includes('--check')
let stale = 0
for (const [name, gen] of outputs) {
  const p = join(OUT, name)
  const text = gen()
  if (check) {
    if (!existsSync(p) || readFileSync(p, 'utf8') !== text) {
      stale++
      console.error(`gen-registry: ui/icons/${name} is out of date; run node tools/shadcn/icons/gen-registry.mjs`)
    }
  } else writeFileSync(p, text)
}
if (stale) process.exit(1)
console.log(`gen-registry: ${check ? 'up to date' : 'wrote'} registry (${INVENTORY.length} keys)`)
