def sub_name(fs: int, sub: int) -> str | None:
    names = FLIGHT_SUB.get(fs, ())
    return names[sub] if 0 <= sub < len(names) else None


def sub_value(fs: int, name: str) -> int:
    return FLIGHT_SUB[fs].index(name)


def time_state(state_byte: int) -> TimeState:
    """Low 4 bits of TIME.state / clock_state; bit7 (REPLAY) is masked (AWR-03 §5.2 rule 6)."""
    return TimeState(state_byte & TimeFlags.STATE_MASK)


def time_is_replay(state_byte: int) -> bool:
    return bool(state_byte & TimeFlags.REPLAY)


def time_advances(state_byte: int) -> bool:
    """SimClockView advances only in PLAYING and LIVE; every other state freezes."""
    return time_state(state_byte) in (TimeState.PLAYING, TimeState.LIVE)


def red_highlight(fs: int, flags: int) -> bool:
    """Swarm-wide red highlight: CORRECTING <= fs <= CRASHED and fs != LANDED, or ALERT (g04 §5.4)."""
    return (FlightState.CORRECTING <= fs <= FlightState.CRASHED and fs != FlightState.LANDED) or bool(flags & FlightFlags.ALERT)
